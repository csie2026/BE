-- Old summaries contain no GPS evidence. Never invent evidence for historical activities.
ALTER TABLE hiking_activities ADD COLUMN gps_recorded BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE hiking_activities ADD COLUMN gps_evidence_hash VARCHAR(64);

CREATE TABLE hiking_activity_scores (
 activity_id BIGINT PRIMARY KEY REFERENCES hiking_activities(id),
 member_id BIGINT NOT NULL REFERENCES members(id),
 mountain_id BIGINT NOT NULL REFERENCES mountains(id),
 certification_date DATE NOT NULL,
 status VARCHAR(32) NOT NULL CHECK(status IN ('CERTIFIED','GPS_REQUIRED','BELOW_MINIMUM','DAILY_LIMIT')),
 visit_points INTEGER NOT NULL CHECK(visit_points IN (0,100,200)),
 summit_points INTEGER NOT NULL CHECK(summit_points IN (0,70)),
 policy_version VARCHAR(64) NOT NULL,
 CHECK((status='CERTIFIED' AND visit_points IN (100,200)) OR (status<>'CERTIFIED' AND visit_points=0 AND summit_points=0))
);
CREATE INDEX activity_scores_member ON hiking_activity_scores(member_id);
CREATE TABLE hiking_daily_certifications (
 member_id BIGINT NOT NULL REFERENCES members(id),
 certification_date DATE NOT NULL,
 activity_id BIGINT NOT NULL UNIQUE REFERENCES hiking_activity_scores(activity_id),
 PRIMARY KEY(member_id, certification_date)
);
CREATE TABLE hiking_public_bonuses (
 member_id BIGINT NOT NULL REFERENCES members(id),
 mountain_id BIGINT NOT NULL REFERENCES mountains(id),
 points INTEGER NOT NULL CHECK(points IN (0,50)),
 policy_version VARCHAR(64) NOT NULL,
 PRIMARY KEY(member_id,mountain_id)
);
-- Append-only changes: activity breakdown plus publication bonus grant/revoke/restore.
CREATE TABLE hiking_score_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 member_id BIGINT NOT NULL REFERENCES members(id),
 activity_id BIGINT REFERENCES hiking_activities(id),
 mountain_id BIGINT REFERENCES mountains(id),
 kind VARCHAR(32) NOT NULL CHECK(kind IN ('ACTIVITY','PUBLIC_BONUS','MEMBER_TOTAL')),
 old_points BIGINT,
 new_points BIGINT NOT NULL CHECK(new_points>=0),
 points_delta BIGINT NOT NULL,
 detail VARCHAR(300) NOT NULL,
 policy_version VARCHAR(64) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX score_events_member ON hiking_score_events(member_id,id);
